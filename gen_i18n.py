#!/usr/bin/env python3
"""Generates src/i18n.js (popup/options: all keys) and src/i18n-content.js (content script: only the few
strings it shows on the page) from locales/*.txt. Run automatically by build.py."""
import json, pathlib

root = pathlib.Path(__file__).parent
loc = root / "locales"
keys = loc.joinpath("keys.txt").read_text(encoding="utf-8").split()
CONTENT_KEYS = ["tab_translate", "tl_stop", "tl_settings", "tl_scanning", "tl_none", "tl_progress", "tl_done", "tl_err", "tl_hint_cc", "p_auto_lang"]
RTL = ["ar", "he", "fa", "ur"]

def load(code):
    lines = loc.joinpath(f"{code}.txt").read_text(encoding="utf-8").rstrip("\n").split("\n")
    assert len(lines) == len(keys), f"{code}: {len(lines)} lines, expected {len(keys)}"
    return dict(zip(keys, lines))

codes = ["en"] + sorted(p.stem for p in loc.glob("*.txt") if p.stem not in ("keys", "en"))
data = {c: load(c) for c in codes}
data["en"]["ext_title"] = "SubBridge"      # brand name, never translated

RUNTIME = '''
const UI_RTL = %s;

// Browser UI language -> one of our locale codes.
function detectUiLang() {
    let raw = "en";
    try { raw = (chrome.i18n && chrome.i18n.getUILanguage && chrome.i18n.getUILanguage()) || navigator.language || "en"; } catch (e) {}
    const l = String(raw).replace("_", "-").toLowerCase();
    if (l.startsWith("zh")) return /^zh-(tw|hk|mo)|hant/.test(l) ? "zh-TW" : "zh-CN";
    const base = l.split("-")[0];
    const alias = { nb: "no", nn: "no", fil: "tl", iw: "he", in: "id" };
    const code = alias[base] || base;
    return Object.prototype.hasOwnProperty.call(I18N, code) ? code : "en";
}
// pref = a locale code, or "auto"/undefined to follow the browser language.
function resolveUiLang(pref) {
    if (pref && pref !== "auto" && Object.prototype.hasOwnProperty.call(I18N, pref)) return pref;
    return detectUiLang();
}
function i18nText(key, pref, vars) {
    const lang = resolveUiLang(pref);
    let str = (I18N[lang] && I18N[lang][key] !== undefined) ? I18N[lang][key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
    if (vars) Object.keys(vars).forEach(k => { str = str.split("{" + k + "}").join(vars[k]); });
    return str;
}
''' % json.dumps(RTL)

def emit(path, dicts, title):
    body = "// " + title + "\n// GENERATED by gen_i18n.py from locales/*.txt - edit the locale files, not this file.\n"
    body += "const I18N = " + json.dumps(dicts, ensure_ascii=False, indent=1) + ";\n" + RUNTIME
    pathlib.Path(path).write_text(body, encoding="utf-8")

emit(root / "src/i18n.js", data, "SubBridge - UI strings for the popup and the settings page (%d languages)" % len(codes))
lite = {c: {k: v for k, v in d.items() if k in CONTENT_KEYS or (c == "en" and k == "ext_title")} for c, d in data.items()}
emit(root / "src/i18n-content.js", lite, "SubBridge - the few UI strings shown on web pages (content script)")
print(f"generated i18n for {len(codes)} languages")
